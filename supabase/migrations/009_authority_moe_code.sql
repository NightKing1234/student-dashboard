-- מיגרציה 009: קוד הרשות במשרד החינוך
--
-- קוד הרשות אצלנו אינו בהכרח הקוד שמשרד החינוך משתמש בו בשמות הקבצים.
-- למשל: "כפר" רשומה אצלנו כ-120, אבל קובצי המצב"ת שלה נקראים ..._5108_...
--
-- בלי לדעת את ההתאמה הזו אי אפשר לזהות את התקלה המסוכנת באמת:
-- העלאת קבצים של מועצה אחת תחת מועצה אחרת, שהייתה דורסת נתונים של
-- רשות שלמה בנתונים זרים — בלי שאף אחד ישים לב.
--
-- הסוכן ממלא את השדה לבד בעדכון הראשון, ומכאן ואילך דורש התאמה.

alter table public.authorities
  add column if not exists moe_code text;

comment on column public.authorities.moe_code is
  'קוד הרשות כפי שמופיע בשמות קובצי המצב"ת. נלמד אוטומטית בעדכון הראשון.';

-- מילוי לרשויות הקיימות שבהן הקוד זהה
update public.authorities
   set moe_code = code
 where moe_code is null
   and code in ('1400000', '800000');

-- כפר: הקוד אצלנו 120, במשרד החינוך 5108
update public.authorities
   set moe_code = '5108'
 where code = '120' and moe_code is null;
